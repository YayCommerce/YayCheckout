#!/usr/bin/env python3
"""Capture templates/layouts/<slug>/preview.html for every catalogue template from the HTML mock.

Each mock template renders only with its own JS, so headless Chrome renders it once and the rendered
DOM is saved with every script removed. The picker shows the result in an iframe that may not run
scripts, and a preview must make no network request, so a file that fails the checks is not written.

Usage:
  capture-template-previews.py [--mock PATH] [--chrome PATH]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOGUE = os.path.join(ROOT, 'includes', 'Controllers', 'LayoutTemplateCatalogue.php')
EXTRACT = os.path.join(ROOT, '.claude', 'skills', 'build-checkout-template', 'scripts', 'extract_mock.py')
TEMPLATES = os.path.join(ROOT, 'templates', 'layouts')

DEFAULT_MOCK = os.path.expanduser('~/Downloads/WooCommerce Checkout Templates_v1.1.html')
DEFAULT_CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'

HEADER = ('<!-- Generated by scripts/capture-template-previews.py from the checkout-templates mock. '
          'Do not edit; re-run ./scripts/run.sh previews. -->\n')

STRIP = [
    re.compile(r'<script\b.*?</script>', re.S | re.I),
    re.compile(r'<noscript\b.*?</noscript>', re.S | re.I),
    re.compile(r'<(\w+)\b[^>]*\bid="__bundler[^"]*"[^>]*>.*?</\1>', re.S),
    re.compile(r'\son[a-z]+="[^"]*"', re.I),
]

FORBIDDEN = [
    re.compile(r'<script', re.I),
    re.compile(r'<noscript', re.I),
    re.compile(r'id="__bundler'),
    re.compile(r'\son[a-z]+=', re.I),
    re.compile(r'\{\{'),
]

# A src or url() whose value is not inline data or a fragment would make the preview fetch something.
EXTERNAL = re.compile(r'''(?:\ssrc=["']|url\(\s*["']?)(?!data:|#)[^"')\s]''', re.I)


def catalogue():
    source = open(CATALOGUE, encoding='utf-8').read()
    return re.findall(r"'slug'\s*=>\s*'([^']+)',\s*'name'\s*=>\s*'([^']+)'", source)


def mock_templates(mock):
    out = subprocess.run([sys.executable, '-I', EXTRACT, '--mock', mock, '--list'],
                         check=True, capture_output=True, text=True).stdout
    return [tuple(line.split(None, 1)) for line in out.splitlines() if line.strip()]


def render(mock, chrome, mock_id, workdir):
    subprocess.run([sys.executable, '-I', EXTRACT, '--mock', mock, mock_id, '--out', workdir],
                   check=True, capture_output=True)
    page = os.path.join(workdir, 't%s.html' % mock_id)
    # Chrome writes allocator noise to stderr on every run.
    return subprocess.run([
        chrome, '--headless=new', '--disable-gpu', '--hide-scrollbars',
        '--user-data-dir=' + os.path.join(workdir, 'profile'),
        '--virtual-time-budget=8000', '--window-size=1280,1800',
        '--dump-dom', 'file://' + page,
    ], check=True, capture_output=True, text=True).stdout


def strip(html):
    for pattern in STRIP:
        html = pattern.sub('', html)
    return html


def problem(html):
    for pattern in FORBIDDEN + [EXTERNAL]:
        match = pattern.search(html)
        if match:
            return html[match.start():match.start() + 60]
    return None


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--mock', default=DEFAULT_MOCK)
    p.add_argument('--chrome', default=DEFAULT_CHROME)
    a = p.parse_args()

    if not os.path.isfile(a.mock):
        sys.exit('Mock not found: %s. Pass --mock <path to the bundle .html>.' % a.mock)
    if not os.path.isfile(a.chrome):
        sys.exit('Chrome not found: %s. Pass --chrome <path to the Chrome binary>.' % a.chrome)

    slugs = {name: slug for slug, name in catalogue()}
    pairs, failed = [], False
    for mock_id, name in mock_templates(a.mock):
        if name not in slugs:
            print('No catalogue template is named %r (mock %s).' % (name, mock_id))
            failed = True
            continue
        pairs.append((mock_id, slugs.pop(name)))
    for name, slug in slugs.items():
        print('No mock template for %s (%r).' % (slug, name))
        failed = True
    if failed:
        sys.exit(1)

    for mock_id, slug in pairs:
        with tempfile.TemporaryDirectory() as workdir:
            html = strip(render(a.mock, a.chrome, mock_id, workdir))
        bad = problem(html)
        if bad:
            print('%-20s FAILED, not written: %r' % (slug, bad))
            failed = True
            continue
        os.makedirs(os.path.join(TEMPLATES, slug), exist_ok=True)
        with open(os.path.join(TEMPLATES, slug, 'preview.html'), 'w', encoding='utf-8') as f:
            f.write(HEADER + html)
        print('%-20s %d KB' % (slug, len(html.encode('utf-8')) // 1024))

    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
