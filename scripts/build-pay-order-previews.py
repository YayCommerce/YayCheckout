#!/usr/bin/env python3
"""Build templates/layouts/<slug>/pay-order-preview.html (templates/layouts/pro/<slug>/ for a Pro template) for every
catalogue template with a design.json.

The page is the shared pay-order page (templates/layouts/pro/pay-order.php) as a shopper sees it from a "Customer payment
page" link, with sample order data, coloured by the template's design.json, as the storefront colours it
(Renderer\\DesignStyles). Express Pay shows nothing here: its buttons are the gateways', and without them the block and
its OR divider hide. The New layout modal shows it in the Pay order card. Like preview.html, it may run no script and
make no request.

Usage:
  build-pay-order-previews.py
"""
import html
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

sys.dont_write_bytecode = True


def _load(name, file):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, file))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


# The catalogue reader and preview checks are capture-template-previews.py's; the design tokens and sample order are
# the thank-you previews', so the two cards show the same order in the same colours. Loaded by path, since -I keeps
# this folder off sys.path.
capture = _load('capture_template_previews', 'capture-template-previews.py')
thank_you = _load('build_thank_you_previews', 'build-thank-you-previews.py')

HEADER = ('<!-- Generated by scripts/build-pay-order-previews.py from the template\'s design.json. '
          'Do not edit; re-run ./scripts/run.sh pay-order-previews. -->\n')

# WooCommerce's sample gateways, as a store with only the core ones lists them; the first is selected.
GATEWAYS = [
    ('Direct bank transfer', 'Make your payment directly into our bank account. Please use your Order ID as the payment '
                             'reference. Your order will not be shipped until the funds have cleared in our account.'),
    ('Check payments', ''),
    ('Cash on delivery', ''),
]
PRIVACY = ('Your personal data will be used to process your order, support your experience throughout this website, '
           'and for other purposes described in our <a>privacy policy</a>.')


def page(name, t):
    rows = ''.join(
        '<tr><td>%s × 1<small>%s</small></td><td>%s</td></tr>' % (html.escape(item), html.escape(variant), price)
        for item, variant, price in thank_you.ITEMS
    )
    totals = ''.join('<tr class="total"><th>%s</th><td>%s</td></tr>' % (label, value) for label, value in thank_you.TOTALS)
    gateways = ''.join(
        '<li%s><span class="radio"></span>%s%s</li>' % (
            ' class="selected"' if index == 0 else '',
            html.escape(label),
            '<p class="box">%s</p>' % html.escape(box) if index == 0 and box else '',
        )
        for index, (label, box) in enumerate(GATEWAYS)
    )
    css = '''
:root{--primary:%(primary)s;--text:%(text)s;--bg:%(background)s;--border:%(border)s;--muted:%(muted)s;--link:%(link)s}
*{box-sizing:border-box}
html,body{margin:0}
body{background:var(--bg);color:var(--text);font-family:%(font)s;font-size:%(size)s;line-height:1.5}
.page{max-width:720px;margin:0 auto;padding:48px 24px;display:flex;flex-direction:column;gap:24px}
.brand{display:flex;align-items:center;gap:8px;font-weight:600;font-size:18px}
.brand i{width:22px;height:22px;border-radius:4px;background:var(--primary);color:#fff;font-style:normal;font-size:13px;display:flex;align-items:center;justify-content:center}
h1{margin:0;font-size:28px;font-weight:600;line-height:1.3}
p{margin:0}
h2{margin:0 0 8px;font-size:1.25em;font-weight:600}
/* Order Details as its block draws it (packages/blocks/src/order-details/editor.css, checkout-base.css): a boxed
   table with rounded corners, the Total column right-aligned, totals' labels bold and their values not. */
.order-details h2{font-weight:400}
table{width:100%%;border:1px solid var(--border);border-radius:5px;border-collapse:separate;border-spacing:0}
th,td{text-align:left;padding:9px 12px;border-top:1px solid var(--border);vertical-align:middle}
thead th{border-top:0}
th{font-weight:700}
:is(th,td):last-child:not(:first-child){text-align:right}
td small{display:block;color:var(--muted);font-size:.85em}
tfoot td{font-weight:400}
ul{list-style:none;margin:0;padding:0;border:1px solid var(--border);border-radius:6px;overflow:hidden}
li{padding:12px 14px;display:flex;flex-wrap:wrap;align-items:center;gap:10px}
li+li{border-top:1px solid var(--border)}
li.selected{box-shadow:inset 0 0 0 1px var(--primary);background:color-mix(in srgb,var(--primary) 7%%,transparent)}
.radio{width:14px;height:14px;border-radius:50%%;border:1px solid var(--muted);flex:none}
li.selected .radio{border:4px solid var(--primary)}
.box{flex-basis:100%%;color:var(--muted);font-size:.92em}
.privacy{color:var(--muted);font-size:.92em}
a{color:var(--link);text-decoration:underline}
button{align-self:flex-start;background:var(--primary);color:#fff;border:0;border-radius:4px;padding:12px 22px;font:inherit;font-weight:600}
''' % t
    return '''<!doctype html>
<html lang="en"><head><meta charset="utf-8">%(csp)s<title>%(name)s: pay for order</title><style>%(css)s</style></head>
<body><div class="page">
<div class="brand"><i>S</i>Storefront</div>
<h1>Pay for order</h1>
<p>Order #: 1042</p>
<section class="order-details"><h2>Order details</h2>
<table><thead><tr><th>Product</th><th>Total</th></tr></thead><tbody>%(rows)s</tbody><tfoot>%(totals)s</tfoot></table>
</section>
<section><h2>Payment</h2><ul>%(gateways)s</ul></section>
<p class="privacy">%(privacy)s</p>
<button type="button">Pay for order</button>
</div></body></html>
''' % {'csp': capture.CSP, 'name': html.escape(name), 'css': css, 'rows': rows, 'totals': totals,
       'gateways': gateways, 'privacy': PRIVACY}


def main():
    failed = False
    for slug, name, is_pro in capture.catalogue():
        # A Pro template lives under pro/, as LayoutTemplateCatalogue::relative_path() places it.
        folder = os.path.join(capture.TEMPLATES, 'pro', slug) if is_pro else os.path.join(capture.TEMPLATES, slug)
        design_file = os.path.join(folder, 'design.json')
        if not os.path.isfile(design_file):
            print('%-20s skipped: no design.json (coming soon)' % slug)
            continue
        with open(design_file, encoding='utf-8') as f:
            out = page(name, thank_you.tokens(json.load(f)))
        bad = capture.problem(out)
        if bad:
            print('%-20s FAILED, not written: %r' % (slug, bad))
            failed = True
            continue
        with open(os.path.join(folder, 'pay-order-preview.html'), 'w', encoding='utf-8') as f:
            f.write(HEADER + out)
        print('%-20s %d KB' % (slug, len(out.encode('utf-8')) // 1024 or 1))
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
