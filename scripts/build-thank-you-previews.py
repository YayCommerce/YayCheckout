#!/usr/bin/env python3
"""Build templates/layouts/<slug>/thank-you-preview.html (templates/layouts/pro/<slug>/ for a Pro template) for every
catalogue template with a design.json.

The page is the shared thank-you page (templates/layouts/pro/thank-you.php) as a shopper sees it after an order, with sample
order data, coloured by the template's design.json, as the storefront colours it (Renderer\\DesignStyles). The New layout
modal shows it in the Thank you card. Like preview.html, it may run no script and make no request.

Usage:
  build-thank-you-previews.py
"""
import html
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# Loading the capture script below would otherwise leave scripts/__pycache__/ behind.
sys.dont_write_bytecode = True

# The catalogue reader and the preview checks are capture-template-previews.py's; loaded by path, since -I keeps
# this folder off sys.path.
_spec = importlib.util.spec_from_file_location('capture_template_previews', os.path.join(HERE, 'capture-template-previews.py'))
capture = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(capture)

HEADER = ('<!-- Generated by scripts/build-thank-you-previews.py from the template\'s design.json. '
          'Do not edit; re-run ./scripts/run.sh thank-you-previews. -->\n')

# LayoutDesign::FONT_STACKS['system'], which every empty or system font_family prints.
SYSTEM_STACK = ('-apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Oxygen-Sans, Ubuntu, Cantarell, '
                '"Helvetica Neue", sans-serif')

# The neutral fallbacks checkout-base.css reads when a token is empty.
FALLBACKS = {
    'primary': '#3858e9',
    'text': '#1e1e1e',
    'background': '#ffffff',
    'border': '#dddddd',
    'muted': '#757575',
}

# The same sample order as the checkout mocks' order summaries.
ITEMS = [('Linen overshirt', 'Olive / M', '$68.00'), ('Canvas tote', 'Natural', '$60.00')]
TOTALS = [('Subtotal:', '$128.00'), ('Shipping:', '$8.00'), ('Tax:', '$10.24'),
          ('Payment method:', 'Direct bank transfer'), ('Total:', '$146.24')]
# templates/layouts/pro/thank-you.php's overview Row of Stacks: label, then the live value as an order fills it.
OVERVIEW = [('Order #:', '1042'), ('Date:', 'October 22, 2026'), ('Total:', '$146.24'), ('Email:', 'jane@example.com'),
            ('Payment method:', 'Direct bank transfer')]
ADDRESS = 'Jane Cooper<br>1901 Thornridge Cir.<br>Shiloh, CA 81063<br>United States (US)'


def tokens(design):
    colours = design.get('colours') or {}
    typography = design.get('typography') or {}
    found = {key: (colours.get(key) or fallback) for key, fallback in FALLBACKS.items()}
    found['link'] = colours.get('link') or found['primary']
    family = typography.get('font_family') or 'system'
    # Every catalogue template uses the system stack today; a picked font can't load in a preview that makes no request.
    found['font'] = SYSTEM_STACK if family == 'system' else '"%s", %s' % (family.replace('-', ' ').title(), SYSTEM_STACK)
    found['size'] = '%dpx' % (typography.get('base_size') or 13)
    return found


def page(name, t):
    rows = ''.join(
        '<tr><td>%s × 1<small>%s</small></td><td>%s</td></tr>' % (html.escape(item), html.escape(variant), price)
        for item, variant, price in ITEMS
    )
    overview = ''.join('<div><p>%s</p><p>%s</p></div>' % (label, html.escape(value)) for label, value in OVERVIEW)
    totals = ''.join('<tr class="total"><th>%s</th><td>%s</td></tr>' % (label, value) for label, value in TOTALS)
    css = '''
:root{--primary:%(primary)s;--text:%(text)s;--bg:%(background)s;--border:%(border)s;--muted:%(muted)s;--link:%(link)s}
*{box-sizing:border-box}
html,body{margin:0}
body{background:var(--bg);color:var(--text);font-family:%(font)s;font-size:%(size)s;line-height:1.5}
.page{max-width:720px;margin:0 auto;padding:48px 24px;display:flex;flex-direction:column;gap:24px}
.brand{display:flex;align-items:center;gap:8px;font-weight:600;font-size:18px}
.brand i{width:22px;height:22px;border-radius:4px;background:var(--primary);color:#fff;font-style:normal;font-size:13px;display:flex;align-items:center;justify-content:center}
h1{margin:0;font-size:28px;font-weight:600;line-height:1.3}
p{margin:0}
.overview{display:flex;flex-wrap:wrap;gap:32px}
h2{margin:0 0 8px;font-size:1.25em;font-weight:600}
table{width:100%%;border-collapse:collapse}
th,td{text-align:left;padding:9px 12px 9px 0;border-top:1px solid var(--border);vertical-align:top}
thead th{border-top:0;font-weight:600}
td small{display:block;color:var(--muted);font-size:.85em}
.total th{font-weight:600}
tfoot tr:last-child th,tfoot tr:last-child td{font-weight:600}
.addresses{display:grid;grid-template-columns:1fr 1fr;gap:24px}
address{font-style:normal}
a{color:var(--link)}
''' % t
    return '''<!doctype html>
<html lang="en"><head><meta charset="utf-8">%(csp)s<title>%(name)s: thank you</title><style>%(css)s</style></head>
<body><div class="page">
<div class="brand"><i>S</i>Storefront</div>
<h1>Thank you. Your order has been received.</h1>
<div class="overview">%(overview)s</div>
<section><h2>Order details</h2>
<table><thead><tr><th>Product</th><th>Total</th></tr></thead><tbody>%(rows)s</tbody><tfoot>%(totals)s</tfoot></table>
</section>
<div class="addresses">
<section><h2>Billing address</h2><address>%(address)s<br><a>jane@example.com</a></address></section>
<section><h2>Shipping address</h2><address>%(address)s</address></section>
</div>
</div></body></html>
''' % {'csp': capture.CSP, 'name': html.escape(name), 'css': css, 'rows': rows, 'overview': overview, 'totals': totals, 'address': ADDRESS}


def main():
    failed = False
    for slug, name, is_pro in capture.catalogue():
        # A Pro template lives under pro/, as LayoutTemplateCatalogue::relative_path() places it.
        folder = os.path.join(capture.TEMPLATES, 'pro', slug) if is_pro else os.path.join(capture.TEMPLATES, slug)
        design_file = os.path.join(folder, 'design.json')
        if not os.path.isfile(design_file):
            print('%-20s skipped: no design.json (coming soon)' % slug)
            continue
        with open(design_file, encoding='utf-8') as f:
            out = page(name, tokens(json.load(f)))
        bad = capture.problem(out)
        if bad:
            print('%-20s FAILED, not written: %r' % (slug, bad))
            failed = True
            continue
        with open(os.path.join(folder, 'thank-you-preview.html'), 'w', encoding='utf-8') as f:
            f.write(HEADER + out)
        print('%-20s %d KB' % (slug, len(out.encode('utf-8')) // 1024 or 1))
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
